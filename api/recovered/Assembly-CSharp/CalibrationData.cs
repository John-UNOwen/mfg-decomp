public class CalibrationData
{
	public float screen_l;

	public float screen_u;

	public float screen_r;

	public float screen_d;

	public float touch_l;

	public float touch_u;

	public float touch_r;

	public float touch_d;

	public CalibrationData()
	{
		screen_l = 0f;
		screen_u = 1080f;
		screen_r = 1920f;
		screen_d = 0f;
		touch_l = 0f;
		touch_u = 1080f;
		touch_r = 1920f;
		touch_d = 0f;
	}
}
