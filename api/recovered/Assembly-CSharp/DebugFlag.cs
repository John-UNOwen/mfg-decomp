	private static ReactiveDictionary<Flag, bool> m_isActives;

	public static IObservable<DictionaryReplaceEvent<Flag, bool>> IsActiveChangedObservable => m_isActives.ObserveReplace();

	static DebugFlag()
	{
		m_isActives = new ReactiveDictionary<Flag, bool>();
	}

	public static bool IsActive(Flag key)
	{
		return false;
	}

	public static void SetActive(Flag key, bool isActive)
	{
		if (m_isActives[key] != isActive)
		{
			m_isActives[key] = isActive;
			PlayerPrefs.SetInt("VFG/DebugFlag/" + key, isActive ? 1 : 0);
		}
	}

	public static void ToggleActive(Flag key)
	{
		SetActive(key, !IsActive(key));
	}
