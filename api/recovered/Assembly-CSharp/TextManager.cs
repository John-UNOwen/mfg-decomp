	public enum LANGUAGE
	{
		JAPANESE,
		ENGLISH
	}

	private static Dictionary<string, string> sDictionary = new Dictionary<string, string>();

	public static void Initialize(LANGUAGE lang)
	{
		string path = lang switch
		{
			LANGUAGE.JAPANESE => "Text/japanese", 
			LANGUAGE.ENGLISH => "Text/english", 
			_ => throw new Exception("TextManager Init failed."), 
		};
		sDictionary.Clear();
		StringReader stringReader = new StringReader(Resources.Load<TextAsset>(path).text);
		while (stringReader.Peek() > -1)
		{
			string[] array = stringReader.ReadLine().Split(',');
			sDictionary.Add(array[0], array[1].Replace("\\n", "\n"));
		}
	}

	public static string Get(KEY key)
	{
		return Get(Enum.GetName(typeof(KEY), key));
	}

	public static string Get(string key)
	{
		return sDictionary[key];
	}
