function List-Section([string]$title, [string]$dir, [string[]]$comment) {
  $files = Get-ChildItem $dir -Filter *.dll | Sort-Object Name
  $mb = [math]::Round(($files | Measure-Object Length -Sum).Sum / 1MB, 2)
  $out = @()
  $out += ('== {0}  ({1} dlls, {2} MB)' -f $title, $files.Count, $mb)
  foreach ($c in $comment) { $out += $c }
  foreach ($f in $files) { $out += ('  {0,-62} {1,9}' -f $f.Name, $f.Length) }
  $out += ''
  $out
}

