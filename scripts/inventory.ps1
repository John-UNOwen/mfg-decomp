# Regenerates docs/inventory/ from the game install (default: the sandbox install path).
# Run from the repo root: pwsh -File scripts/inventory.ps1
param(
  [string]$Install = '\\MYAPPSANDBOX\c\Games\MFG',
  [string]$OutDir = 'docs/inventory'
)
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $OutDir | Out-Null

function StringsOf([string]$path) {
  [Text.Encoding]::GetEncoding(28591).GetString([IO.File]::ReadAllBytes($path))
}

$managed = Join-Path $Install 'game\MFGClient_Data\Managed'
$mods    = Join-Path $Install 'modules'
$plug    = Join-Path $Install 'game\MFGClient_Data\Plugins\x86_64'

Get-ChildItem $managed -Filter *.dll | Sort-Object Name | ForEach-Object {
  [pscustomobject]@{ Name = $_.Name; KB = [math]::Round($_.Length / 1KB, 1) }
} | Export-Csv (Join-Path $OutDir 'assemblies.csv') -NoTypeInformation

Get-ChildItem $mods -File -Include *.dll, *.exe | ForEach-Object {
  [pscustomobject]@{ Dir = 'modules'; Name = $_.Name; KB = [math]::Round($_.Length / 1KB, 1) }
} | Export-Csv (Join-Path $OutDir 'native-modules.csv') -NoTypeInformation
Get-ChildItem $plug -File | ForEach-Object {
  [pscustomobject]@{ Dir = 'Plugins/x86_64'; Name = $_.Name; KB = [math]::Round($_.Length / 1KB, 1) }
} | Export-Csv (Join-Path $OutDir 'native-modules.csv') -NoTypeInformation -Append

# API surface: symbols and path keys the managed layer exchanges with the native arcade stack
$ac   = StringsOf (Join-Path $managed 'Assembly-CSharp.dll')
$kam  = StringsOf (Join-Path $managed 'kamunity.dll')
$cfg  = Get-Content (Join-Path $Install 'dev\nvram\ea3-config.xml') -Raw

$ea3Names = (([regex]::Matches("$ac$kam", 'ea3_[A-Za-z_0-9]+') | ForEach-Object Value) | Sort-Object -Unique)
$events   = (([regex]::Matches("$ac$kam$cfg", 'VFG\.[A-Za-z0-9_.]+') | ForEach-Object Value) | Sort-Object -Unique)
$paths    = (([regex]::Matches("$ac$kam", '/(?:ea3|opt|coin|env|sntp|keepalive|sys|board)[A-Za-z0-9_/.\-]*') | ForEach-Object Value) | Sort-Object -Unique)

$md = [System.Collections.Generic.List[string]]::new()
$md.Add("# ea3 / eAC3 API surface (generated by scripts/inventory.ps1)")
$md.Add("")
$md.Add("Evidence sources: managed Assembly-CSharp.dll, managed kamunity.dll, live dev/nvram/ea3-config.xml.")
$md.Add("Recovered wrapper C# (richer detail): api/recovered/.")
$md.Add("")
$md.Add("## ea3_* symbols referenced ($($ea3Names.Count))")
$md.Add("")
$ea3Names | ForEach-Object { $md.Add("- $_") }
$md.Add("")
$md.Add("## POS / billing event names ($($events.Count))")
$md.Add("")
$events | ForEach-Object { $md.Add("- $_") }
$md.Add("")
$md.Add("## Property paths in managed code ($($paths.Count), first 200)")
$md.Add("")
$paths | Select-Object -First 200 | ForEach-Object { $md.Add("- ``$_``") }
$md.Add("")
$bundles = (Get-ChildItem (Join-Path $Install 'game\MFGClient_Data\StreamingAssets\aa\StandaloneWindows64') -File).Count
$catalog = (Get-Item (Join-Path $Install 'game\MFGClient_Data\StreamingAssets\aa\catalog.json')).Length
$md.Add("## Content stats")
$md.Add("")
$md.Add("- Addressables bundles: $bundles (plain UnityFS, 2022.3.13f1)")
$md.Add("- catalog.json: $([math]::Round($catalog/1MB,1)) MB")
Set-Content -Path (Join-Path $OutDir 'api_surface.md') -Value $md -Encoding utf8

"generated: assemblies.csv, native-modules.csv, api_surface.md -> $OutDir"
