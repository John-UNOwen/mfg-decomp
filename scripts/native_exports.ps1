# Dumps the PE export tables of the native Konami DLLs the game binds to dynamically.
# The managed wrapper resolves these by name (GetProcAddress), so the export lists ARE the
# native API surface the rebuilt platform layer must cover. Run from repo root.
param(
  [string]$Install = '..',
  [string]$OutDir = 'docs/inventory',
  [string[]]$Targets = @('kamunity.dll', 'avs2-core.dll', 'avs2-ea3.dll', 'kws.dll', 'execexe.dll', 'libaio.dll')
)
$ErrorActionPreference = 'Stop'

function Get-PeExports([string]$path) {
  $b = [IO.File]::ReadAllBytes($path)
  $e = [BitConverter]::ToInt32($b, 60)
  if ([BitConverter]::ToUInt16($b, $e) -ne 0x4550) { throw "not PE: $path" }
  $nsec  = [BitConverter]::ToUInt16($b, $e + 6)
  $sizeOpt = [BitConverter]::ToUInt16($b, $e + 20)
  $opt = $e + 24
  $ddOff = if ([BitConverter]::ToUInt16($b, $opt) -eq 0x20B) { 112 } else { 96 }
  $expRva  = [BitConverter]::ToUInt32($b, $opt + $ddOff)
  $sections = $opt + $sizeOpt
  function RvaToOff([uint32]$rva) {
    for ($i = 0; $i -lt $nsec; $i++) {
      $s = $sections + $i * 40
      $va  = [BitConverter]::ToUInt32($b, $s + 12)
      $raw = [BitConverter]::ToUInt32($b, $s + 20)
      $sz  = [Math]::Max([BitConverter]::ToUInt32($b, $s + 8), [BitConverter]::ToUInt32($b, $s + 16))
      if ($rva -ge $va -and $rva -lt ($va + $sz)) { return $raw + ($rva - $va) }
    }
    throw "rva outside sections: $rva in $path"
  }
  function ReadCStr([int]$off) {
    $sb = [Text.StringBuilder]::new()
    while ($b[$off] -ne 0) { [void]$sb.Append([char]$b[$off]); $off++ }
    $sb.ToString()
  }
  if ($expRva -eq 0) { return @() }
  $d = RvaToOff $expRva
  $numFuncs = [BitConverter]::ToUInt32($b, $d + 20)
  $numNames = [BitConverter]::ToUInt32($b, $d + 24)
  $namesRva = [BitConverter]::ToUInt32($b, $d + 32)
  $namesOff = RvaToOff $namesRva
  0..($numNames - 1) | ForEach-Object { ReadCStr (RvaToOff ([BitConverter]::ToUInt32($b, $namesOff + $_ * 4))) } | Sort-Object
}

$md = [System.Collections.Generic.List[string]]::new()
$md.Add("# Native export tables (generated by scripts/native_exports.ps1)")
$md.Add("")
$md.Add("These are the DLLs the managed layer resolves by name at runtime. The browser port must")
$md.Add("either reimplement or stub every name listed here (classification happens in docs/10, Phase 1).")
$md.Add("")
foreach ($t in $Targets) {
  $p = Join-Path $Install ("modules\" + $t)
  if (-not (Test-Path $p)) { $p = Join-Path $Install ("game/MFGClient_Data/Plugins/x86_64/" + $t) }
  if (-not (Test-Path $p)) { continue }
  $names = @(Get-PeExports $p)
  $md.Add("## $t ($($names.Count) exports)")
  $md.Add("")
  foreach ($n in $names) { $md.Add("- $n") }
  $md.Add("")
}
New-Item -ItemType Directory -Force $OutDir | Out-Null
Set-Content (Join-Path $OutDir 'native_exports.md') -Value $md -Encoding utf8
$md | Where-Object { $_ -like '## *' }
